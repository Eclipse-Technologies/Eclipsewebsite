  <section class="container" style="margin-top:1.5rem;">
    <h2 style="font-family:'Montserrat',sans-serif;color:#003366;margin-bottom:1rem;">What "worker/polisher" means</h2>
    <p style="margin-bottom:1rem;">A worker/polisher (also called lead/lag) setup places two mixed-bed tanks in series. Water flows through the <strong>worker</strong> first, which removes most of the contaminants. The <strong>polisher</strong> then captures whatever passes through.</p>
    <p><strong>Incoming water → Tank 1 (worker) → Tank 2 (polisher) → treated water</strong></p>
  </section>

  <section class="container" style="margin-top:1.5rem;">
    <h2 style="font-family:'Montserrat',sans-serif;color:#003366;margin-bottom:1rem;">Why two tanks instead of one</h2>
    <ol style="padding-left:1.2rem;">
      <li style="margin-bottom:0.6rem;"><strong>More of the resin is used.</strong> A single tank must be changed or regenerated as soon as it begins to break through, even though some capacity remains. With two tanks in series, the worker can run until it is exhausted (for example, when the quality indicator reaches its set point), because the polisher continues to protect the water quality.</li>
      <li style="margin-bottom:0.6rem;"><strong>Planned swaps instead of urgent ones.</strong> When the worker breaks through, the polisher keeps treating the water, so the swap can be scheduled rather than done in a rush.</li>
      <li style="margin-bottom:0.6rem;"><strong>Less need for early changeouts.</strong> With a single tank, operators sometimes change the resin early as a safety margin, which leaves capacity unused. A polisher provides that margin without discarding usable resin.</li>
      <li style="margin-bottom:0.6rem;"><strong>Staged swapping.</strong> When the worker is spent, it is replaced and the partly used polisher moves into the worker position. The fresh tank becomes the new polisher, so the tank that has done the most work is always the one being used up.</li>
      <li><strong>Lower risk of out-of-specification water.</strong> If a single tank is not changed in time, water quality can fall below specification, which can lead to spoiled product, equipment damage or failed quality checks. A second tank reduces that risk, and the quality indicator shows when the worker is spent.</li>
    </ol>
  </section>

